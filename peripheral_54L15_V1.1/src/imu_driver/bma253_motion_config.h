/*
 * BMA253 运动检测参数配置
 *
 * 【平时只需要改这个文件，不用动驱动和示例代码】
 *
 * 阈值以"毫重力加速度 (mg)"为单位，1 g = 1000 mg。
 * 驱动会按当前量程自动换算成芯片寄存器值：
 *     FS=2g  -> 16 mg/LSB
 *     FS=4g  -> 32 mg/LSB      <- 你当前用的是 ±4g
 *     FS=8g  -> 64 mg/LSB
 *     FS=16g -> 128 mg/LSB
 *
 * SPDX-License-Identifier: LicenseRef-Nordic-5-Clause
 */

#ifndef BMA253_MOTION_CONFIG_H
#define BMA253_MOTION_CONFIG_H

/*
 * ============ 运动检测阈值（调这一个就行）============
 *
 * 阈值以**动态加速度**为准（驱动已自动使能 AOI1 高通滤波 HPIS1，
 * 重力直流分量会被滤掉），所以阈值就是"晃动的剧烈程度"。
 *
 * 参考量级（±4g 量程，1 LSB = 32 mg）：
 *     32 mg   芯片最小分辨率（1 LSB）—— 极灵敏，容易误触发
 *     60 mg   很灵敏，桌面轻敲会触发
 *    100 mg   轻碰 / 拿起板子               <- 当前默认值
 *    250 mg   明显晃动 / 走动时的振动
 *    500 mg   用力拍一下
 *   1000 mg   1g，接近猛烈撞击才触发
 *   4064 mg   该量程上限（127 LSB × 32 mg）
 *
 * 【只开高事件】驱动只使能 XH/YH/ZH（超过阈值即触发），
 * 没有开低事件。原因：静止时轴值接近 0g，0 永远小于阈值，
 * 低事件会持续为真 → 中断常亮不跳变，唤醒也会失效。
 *
 * 调参方向：
 *   误触发（没动也报）→ 加大阈值
 *   该触发的不触发    → 减小阈值，或把 BMA253_MOTION_DURATION 改成 1
 */
#define BMA253_MOTION_THRESHOLD_MG      100U

/*
 * ============ 防抖：需连续满足几个采样周期 ============
 *
 * BMA253 要求持续时间不能为 0，否则运动检测不工作（驱动会自动纠正为 1）。
 * ODR=100Hz 时，1 个周期 = 10ms，所以：
 *     1   立即触发（最灵敏，默认）
 *     3   需持续 30ms 才算运动（能滤掉单次毛刺）
 *     10  需持续 100ms（比较"稳"的动作才算）
 */
#define BMA253_MOTION_DURATION          1U

/*
 * ============ 检测模式 ============
 *
 * BMA253_AOI_MODE_OR       任一轴超过阈值即中断（运动检测，推荐）
 * BMA253_AOI_MODE_AND      所有使能轴都超过阈值才中断
 * BMA253_AOI_MODE_6D_MOVE  6 个方向运动识别
 * BMA253_AOI_MODE_6D_POS   6 个方向位置检测（姿态变化）
 *
 * 说明：驱动只使能 XH/YH/ZH 三个高事件，配合 OR 模式即
 * "任一轴动态加速度超过阈值 → INT1 拉高"。
 *
 * ============ 用于中断唤醒时的注意点 ============
 *
 * 1) 中断已配置为**锁存**（LIR_INT1=1）：触发后 INT1 保持高电平，
 *    直到读取 AOI1_SRC(0x31)。这样 MCU 唤醒过程中不会丢事件。
 *    代码里的 bma253_motion_read_src() 就是用来清除锁存的。
 *
 * 2) 如果用 System ON idle 休眠：任意 GPIO 中断都能唤醒，P0.00 可用，
 *    唤醒后原地继续执行，不用重启 —— **推荐**。
 *    需要在 prj.conf 里加：
 *        CONFIG_PM=y
 *        CONFIG_PM_DEVICE=y
 *
 * 3) 如果用 System OFF：只有 **P0/P1** 的引脚能唤醒（P2 不支持
 *    sense 机制），P0.00 属于 P0 所以可用。但 System OFF 唤醒后
 *    等于复位重启，需要重新初始化。
 *
 * 4) 唤醒前务必确认 BMA253 的 ODR 不要是掉电模式（ODR=0000），
 *    否则传感器不采样、也就不会有中断。
 */
#define BMA253_MOTION_MODE              BMA253_AOI_MODE_OR

#endif /* BMA253_MOTION_CONFIG_H */
